import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');

function writeViaTmp(file, content) {
  const tmp = file + '.tmp';
  fs.writeFileSync(tmp, content);
  try { fs.unlinkSync(file); } catch {}
  fs.renameSync(tmp, file);
}

function copyViaTmp(src, dest) {
  writeViaTmp(dest, fs.readFileSync(src));
}

function replaceInFile(p, from, to) {
  const s = fs.readFileSync(p, 'utf8');
  if (!s.includes(from)) {
    console.log('skip/missing', p, from);
    return;
  }
  writeViaTmp(p, s.replaceAll(from, to));
  console.log('patched', p, from, '->', to);
}

function prependNotes(file) {
  const note =
    'CityLoop Quest Mons - Release notes\r\n' +
    'Version 26.08.148\r\n' +
    '----------------------------------------\r\n' +
    'Pelles a enfourner 1573 : texte long réécrit (sans répéter le court), 10 langues + audio long.\r\n\r\n';
  const cur = fs.readFileSync(file, 'utf8');
  if (cur.includes('Version 26.08.148')) {
    console.log('notes already 148', file);
    return;
  }
  writeViaTmp(file, note + cur);
  console.log('notes', file);
}

const ver = fs.readFileSync(path.join(ROOT, 'version.js'), 'utf8');
const sw = fs.readFileSync(path.join(ROOT, 'service-worker.js'), 'utf8');
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const verM = ver.match(/APP_VERSION\s*=\s*'([^']+)'/);
const swM = sw.match(/precache-(v\d+-ot)/);
const epM = html.match(/ot-sw-v\d+/);
console.log('real before', { version: verM && verM[1], precache: swM && swM[1], epoch: epM && epM[0] });
if (!verM || verM[1] !== '26.08.147') throw new Error('version inattendue: ' + (verM && verM[1]));
if (!swM || swM[1] !== 'v89-ot') throw new Error('precache inattendu: ' + (swM && swM[1]));
if (!epM || epM[0] !== 'ot-sw-v46') throw new Error('epoch inattendue: ' + (epM && epM[0]));

writeViaTmp(
  path.join(ROOT, 'version.js'),
  "// Auto-generated by build.mjs\nwindow.APP_VERSION = '26.08.148';\n",
);
replaceInFile(path.join(ROOT, 'service-worker.js'), 'v89-ot', 'v90-ot');
for (const f of ['index.html', 'main.html', 'parcours.html']) {
  replaceInFile(path.join(ROOT, f), 'ot-sw-v46', 'ot-sw-v47');
}
prependNotes(path.join(ROOT, 'Release notes.txt'));

copyViaTmp(path.join(ROOT, 'version.js'), path.join(ROOT, 'dist', 'version.js'));
copyViaTmp(path.join(ROOT, 'service-worker.js'), path.join(ROOT, 'dist', 'service-worker.js'));
copyViaTmp(path.join(ROOT, 'index.html'), path.join(ROOT, 'dist', 'index.html'));
copyViaTmp(path.join(ROOT, 'main.html'), path.join(ROOT, 'dist', 'main.html'));
copyViaTmp(path.join(ROOT, 'parcours.html'), path.join(ROOT, 'dist', 'parcours.html'));
copyViaTmp(path.join(ROOT, 'Release notes.txt'), path.join(ROOT, 'dist', 'Release notes.txt'));
copyViaTmp(
  path.join(ROOT, 'translations', 'descriptions.json'),
  path.join(ROOT, 'dist', 'translations', 'descriptions.json'),
);
copyViaTmp(
  path.join(ROOT, 'data', 'pelles_a_enfourner_1573.txt'),
  path.join(ROOT, 'dist', 'data', 'pelles_a_enfourner_1573.txt'),
);

console.log('bumped 26.08.148 / v90-ot / ot-sw-v47');
